struct NamedPalette
{
    QString key;                     // canonical lowercase
    QString displayName;             // pretty label for combobox
    const QList<QColor> &(*get)();
};

const std::array<NamedPalette, 8> &builtinTable()
{
    static const std::array<NamedPalette, 8> table = {{
        {QStringLiteral("default"),  QStringLiteral("Default"),  &tab10},
        {QStringLiteral("plotly"),   QStringLiteral("Plotly"),   &plotlyPalette},
        {QStringLiteral("d3"),       QStringLiteral("D3"),       &d3Palette},
        {QStringLiteral("g10"),      QStringLiteral("G10"),      &g10Palette},
        {QStringLiteral("t10"),      QStringLiteral("T10"),      &t10Palette},
        {QStringLiteral("alphabet"), QStringLiteral("Alphabet"), &alphabetPalette},
        {QStringLiteral("dark24"),   QStringLiteral("Dark24"),   &dark24Palette},
        {QStringLiteral("light24"),  QStringLiteral("Light24"),  &light24Palette},
    }};
    return table;
}

