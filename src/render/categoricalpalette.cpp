QColor at(int index)
{
    const QList<QColor> &p = tab10();
    const int n = p.size();
    int i = index % n;
    if (i < 0) i += n;
    return p.at(i);
}

int size()
{
    return tab10().size();
}

QList<QColor> palette()
{
    return tab10();
}

QList<QColor> byName(const QString &name)
{
    const QString key = name.trimmed().toLower();
    for (const NamedPalette &e : builtinTable())
        if (e.key == key)
            return e.get();
    return tab10();   // fallback: default palette
}

QStringList builtinNames()
{
    QStringList out;
    out.reserve(static_cast<int>(builtinTable().size()));
    for (const NamedPalette &e : builtinTable())
        out.append(e.displayName);
    return out;
}

